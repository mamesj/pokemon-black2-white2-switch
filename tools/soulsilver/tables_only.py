#!/usr/bin/env python3
"""Makes a copy of gen/ without the recompiled code and without the game's code, for a
SoulSilver or HeartGold build that runs on melonDS's JIT (--jit) or interpreter (--interp).

    python3 tools/soulsilver/tables_only.py gen gen-tables

Without the recompiled code the game still needs to be told which of its functions and overlays
run, for its layouts (the X menu, the Bag, battles, the widescreen overworld): the runtime gets
that from the core's watch on their addresses (rc_watch_attach in runtime/recomp_rt.cpp), using
the chunk table in gen/rc_tables.cpp. Overlays loaded at the same addresses are told apart by
their code, which is read from the player's own ROM when the program starts (rc_portable_load),
so the output holds addresses only: nothing of the game. The same build plays HeartGold (US):
its code is SoulSilver's with a few stretches moved, listed in tools/soulsilver/heartgold-us.json
(tools/soulsilver/match_heartgold.py).

This copies the chunk table and the application table, drops the 1.7 million recompiled
instructions (gen/rc_NNN.cpp) and the code images, and adds rc_portable.cpp: per section, its
overlay in the ROM (from layouts/soulsilver-us.json), and the games the tables serve. The build
then takes a couple of minutes instead of a quarter of an hour, and the program is about a
tenth of the size.

Build with it as with gen/:  cmake ... -DSSR_JIT=ON -DSSR_GENERATED_DIR=<out dir>
"""
import json
import os
import re
import shutil
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    tables = os.path.join(src, 'rc_tables.cpp')
    if not os.path.isfile(tables):
        sys.exit(f'{tables} is missing: run tools/recomp.py first')
    os.makedirs(out, exist_ok=True)

    shutil.copyfile(os.path.join(src, 'apps_table.cpp'), os.path.join(out, 'apps_table.tmp'))
    os.replace(os.path.join(out, 'apps_table.tmp'), os.path.join(out, 'apps_table.cpp'))

    decl = re.compile(r'^void rc_s\d+_[0-9A-F]+\(')
    image_decl = re.compile(r'^extern const unsigned char rc_image_\d+\[\];')
    fn = re.compile(r', rc_s\d+_[0-9A-F]+\}')
    image = re.compile(r', rc_image_\d+, ')
    lines = []
    chunks = 0
    sections = []
    with open(tables) as f:
        for line in f:
            if decl.match(line) or image_decl.match(line):
                continue
            line, n = fn.subn(', nullptr}', line)
            chunks += n
            line = image.sub(', nullptr, ', line)
            m = re.match(r'\s*\{"(\w+)", 0x[0-9A-F]+u, 0x[0-9A-F]+u, nullptr, ', line)
            if m:
                sections.append(m.group(1))
            lines.append(line)

    here = os.path.dirname(os.path.abspath(__file__))
    layout = json.load(open(os.path.join(here, '..', '..', 'layouts', 'soulsilver-us.json')))
    source = {e['name']: e['source'] for e in layout['sections']}
    original_ends = {e['name']: e['base'] + e['size'] for e in layout['sections']}
    minimum_bases = {e['name']: e['base'] for e in layout['sections']}
    overlay_of = [int(source[n]) if source.get(n, 'main') not in ('main', 'itcm') else -1 for n in sections]
    games = [('IPGE', 'Pokemon SoulSilver (USA)', {})]
    for name in sorted(os.listdir(here)):
        if name.endswith('.json'):
            alt = json.load(open(os.path.join(here, name)))
            games.append((alt['code'], alt['game'], alt['shifts']))
            for section, base in alt.get('overlay_bases', {}).items():
                minimum_bases[section] = min(minimum_bases[section], base)
    def align_section(match):
        name = match.group(1)
        if name not in minimum_bases:
            return match.group(0)  # BIOS metadata is not part of the ROM layout.
        base = minimum_bases[name]
        end = int(match.group(2), 16) + int(match.group(3), 16)
        return f'{{"{name}", 0x{base:08X}u, 0x{end-base:X}u, nullptr,'
    table_text = re.sub(r'\{"(\w+)", 0x([0-9A-F]+)u, 0x([0-9A-F]+)u, nullptr,', align_section, ''.join(lines))
    write_if_changed(os.path.join(out, 'rc_tables.cpp'), table_text)
    count = re.search(r'rc_num_chunks = (\d+)', table_text)
    if count:
        chunks = int(count.group(1))
    text = ['// Generated by tools/soulsilver/tables_only.py. Addresses only: the code is read from the ROM.',
            '#include "recomp_api.h"', '', 'namespace', '{',
            'const int overlayOf[] = {' + ', '.join(map(str, overlay_of)) + '};']
    entries = []
    for g, (code, title, shifts) in enumerate(games):
        rows = [f'    {{"{sec}", 0x{a:08X}u, 0x{b:08X}u, {d}}},' for sec, segs in sorted(shifts.items()) for a, b, d in segs]
        text.append(f'const RcPortableShift shifts{g}[] = {{')
        text += rows or ['    {"", 0, 0, 0},']
        text.append('};')
        entries.append(f'    {{"{code}", "{title}", shifts{g}, {len(rows)}}},')
    text += ['const RcPortableGame games[] = {'] + entries + ['};',
             f'const RcPortable portable = {{ overlayOf, games, {len(games)} }};',
             'const bool registered = rc_register_portable(&portable);', '}', '']
    write_if_changed(os.path.join(out, 'rc_portable.cpp'), '\n'.join(text))
    bases = [(source[name], minimum_bases[name]) for name in sections if isinstance(source.get(name), int)]
    header = ['// Generated address metadata for padding ROM overlay images.', '#pragma once',
              'inline unsigned PortableOverlayBase(int id) {', '    switch (id) {']
    header += [f'    case {oid}: return 0x{base:08X}u;' for oid, base in bases]
    header += ['    default: return 0;', '    }', '}',
               'inline unsigned PortableOverlaySize(int id) {', '    switch (id) {']
    header += [f'    case {source[name]}: return 0x{original_ends[name]-minimum_bases[name]:X}u;' for name in sections if isinstance(source.get(name), int)]
    header += ['    default: return 0;', '    }', '}', '']
    write_if_changed(os.path.join(out, 'portable_images.h'), '\n'.join(header))
    write_if_changed(os.path.join(out, 'sources.cmake'),
                     'set(RC_GENERATED_SOURCES\n'
                     '    "${CMAKE_CURRENT_LIST_DIR}/rc_tables.cpp"\n'
                     '    "${CMAKE_CURRENT_LIST_DIR}/rc_portable.cpp"\n'
                     ')\n')
    print(f'{out}: {chunks} chunks, no recompiled code, no game code; games: ' + ', '.join(g[1] for g in games))


def write_if_changed(path, text):
    try:
        if open(path).read() == text:
            return
    except OSError:
        pass
    with open(path, 'w', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    main()
