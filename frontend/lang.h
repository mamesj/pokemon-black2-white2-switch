// The program's own text (menus, the game list, its settings, messages) in the player's
// language. It is written in English where it is used; Tr gives it in Italian when that is the
// language chosen (LANGUAGE in the settings: AUTO follows the system's), from the table below,
// or as it is when the table has no translation (game and key names, cheats). The menus call
// Tr where they draw their text, so only text put together from pieces needs it where it is
// made, each piece looked up on its own.
