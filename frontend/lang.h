// The setting: "auto", "en" or "it".
inline std::string& Choice()
{
    static std::string c = "auto";
    return c;
}
inline void Set(const std::string& v) { Choice() = v == "en" || v == "it" ? v : "auto"; }

// The language= line of a settings file, before anything is drawn (the game list).
inline void Load(const std::string& cfgPath)
{
    if (FILE* f = fopen(cfgPath.c_str(), "r"))
    {
        char line[256];
        while (fgets(line, sizeof line, f))
            if (!strncmp(line, "language=", 9))
            {
                std::string v = line + 9;
                while (!v.empty() && (v.back() == '\n' || v.back() == '\r')) v.pop_back();
                Set(v);
            }
        fclose(f);
    }
}

// Whether the system's first language is Italian (asked once).
inline bool SystemItalian()
{
    static int italian = -1;
    if (italian < 0)
    {
        italian = 0;
        if (SDL_Locale* l = SDL_GetPreferredLocales())
        {
            italian = l[0].language && !strcmp(l[0].language, "it");
            SDL_free(l);
        }
    }
    return italian == 1;
}

inline bool Italian() { return Choice() == "it" || (Choice() == "auto" && SystemItalian()); }

// The name of the setting's value as the menus show it.
inline const char* ChoiceName()
{
    return Choice() == "en" ? "ENGLISH" : Choice() == "it" ? "ITALIANO" : "AUTO";
}

